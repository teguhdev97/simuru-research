from __future__ import annotations

import re
import smtplib
import time
from email.message import EmailMessage
from urllib.parse import quote, urlparse

import httpx

OTP_PATTERN = re.compile(r"SIMURU-QA-OTP:\s*(\d{6})")
LOOPBACK_HOSTS = {"127.0.0.1", "::1", "localhost"}


class MailpitError(RuntimeError):
    """Raised when the local Mailpit SMTP or HTTP API is unavailable."""


class MailpitEmailProvider:
    """Send QA verification emails to local Mailpit and read them through its API."""

    def __init__(
        self,
        *,
        smtp_host: str = "127.0.0.1",
        smtp_port: int = 1025,
        api_url: str = "http://127.0.0.1:8025",
        from_email: str = "no-reply@simuru.local",
        timeout_seconds: float = 5.0,
        poll_timeout_seconds: float = 15.0,
        poll_interval_seconds: float = 0.25,
    ) -> None:
        parsed = urlparse(api_url)
        if parsed.scheme != "http" or parsed.hostname not in LOOPBACK_HOSTS:
            raise ValueError("Mailpit API URL must use HTTP on a loopback host.")
        if smtp_host not in LOOPBACK_HOSTS:
            raise ValueError("Mailpit SMTP host must be a loopback host.")
        if not 1 <= smtp_port <= 65535:
            raise ValueError("Mailpit SMTP port must be between 1 and 65535.")
        if timeout_seconds <= 0 or poll_timeout_seconds <= 0 or poll_interval_seconds <= 0:
            raise ValueError("Mailpit timeouts and polling intervals must be positive.")

        self.smtp_host = smtp_host
        self.smtp_port = smtp_port
        self.api_url = api_url.rstrip("/")
        self.from_email = from_email
        self.timeout_seconds = timeout_seconds
        self.poll_timeout_seconds = poll_timeout_seconds
        self.poll_interval_seconds = poll_interval_seconds

    def check_connection(self) -> dict[str, object]:
        """Check both the local SMTP listener and Mailpit HTTP API."""
        try:
            with smtplib.SMTP(
                self.smtp_host,
                self.smtp_port,
                timeout=self.timeout_seconds,
            ) as smtp:
                status, _ = smtp.noop()
                if status != 250:
                    raise MailpitError("Mailpit SMTP health check was rejected.")

            response = httpx.get(
                f"{self.api_url}/api/v1/info",
                timeout=self.timeout_seconds,
            )
            response.raise_for_status()
            payload = response.json()
        except (OSError, smtplib.SMTPException, httpx.HTTPError, ValueError) as exc:
            if isinstance(exc, MailpitError):
                raise
            raise MailpitError(
                "Mailpit is not reachable. Start the local Mailpit service and "
                "check ports 1025 (SMTP) and 8025 (HTTP API)."
            ) from exc

        if not isinstance(payload, dict):
            raise MailpitError("Mailpit returned an unexpected health response.")
        return payload

    def send_verification_code(
        self,
        *,
        recipient: str,
        code: str,
        run_id: str,
        job_index: int,
    ) -> None:
        """Send one QA OTP through SMTP; Mailpit captures it without external delivery."""
        self._validate_recipient(recipient)
        if not re.fullmatch(r"\d{6}", code):
            raise ValueError("Verification code must contain exactly six digits.")

        message = EmailMessage()
        message["From"] = self.from_email
        message["To"] = recipient
        message["Subject"] = "Simuru Research - QA email verification"
        message["X-Simuru-QA-Run-ID"] = run_id
        message["X-Simuru-QA-Job-Index"] = str(job_index)
        message.set_content(
            "This message was generated by the Simuru Research local QA environment.\n\n"
            f"Verification code: {code}\n"
            f"SIMURU-QA-OTP: {code}\n\n"
            "This is a test-only email captured by your local Mailpit instance. "
            "It is not sent to a real mailbox."
        )

        try:
            with smtplib.SMTP(
                self.smtp_host,
                self.smtp_port,
                timeout=self.timeout_seconds,
            ) as smtp:
                smtp.send_message(message)
        except (OSError, smtplib.SMTPException) as exc:
            raise MailpitError(
                "Could not send the QA email to Mailpit SMTP. "
                "Check that the local SMTP service is running on port 1025."
            ) from exc

    def wait_for_verification_code(self, *, recipient: str) -> str:
        """Poll Mailpit's local REST API and extract the OTP from the captured email."""
        self._validate_recipient(recipient)
        deadline = time.monotonic() + self.poll_timeout_seconds

        while time.monotonic() < deadline:
            try:
                response = httpx.get(
                    f"{self.api_url}/api/v1/messages",
                    params={"start": 0, "limit": 100},
                    timeout=self.timeout_seconds,
                )
                response.raise_for_status()
                payload = response.json()
                messages = payload.get("messages", [])
                if not isinstance(messages, list):
                    raise MailpitError("Mailpit returned an invalid message list.")

                for summary in messages:
                    if not self._message_is_for_recipient(summary, recipient):
                        continue
                    message_id = summary.get("ID")
                    if not isinstance(message_id, str) or not message_id:
                        continue

                    detail_response = httpx.get(
                        f"{self.api_url}/api/v1/message/{quote(message_id, safe='')}",
                        timeout=self.timeout_seconds,
                    )
                    detail_response.raise_for_status()
                    detail = detail_response.json()
                    body = str(detail.get("Text") or "")
                    match = OTP_PATTERN.search(body)
                    if match:
                        return match.group(1)
            except (httpx.HTTPError, ValueError, TypeError) as exc:
                raise MailpitError(
                    "Could not read the QA email from Mailpit's local API. "
                    "Check that the Mailpit HTTP service is running on port 8025."
                ) from exc

            time.sleep(self.poll_interval_seconds)

        raise MailpitError(
            f"Timed out waiting for the QA email addressed to {recipient} in Mailpit."
        )

    @staticmethod
    def _message_is_for_recipient(message: object, recipient: str) -> bool:
        if not isinstance(message, dict):
            return False
        recipients = message.get("To", [])
        if not isinstance(recipients, list):
            return False
        return any(
            isinstance(address, dict)
            and str(address.get("Address", "")).strip().lower() == recipient.lower()
            for address in recipients
        )

    @staticmethod
    def _validate_recipient(recipient: str) -> None:
        clean_recipient = recipient.strip().lower()
        if not re.fullmatch(r"[a-z0-9._+-]+@example\.test", clean_recipient):
            raise ValueError("Mailpit QA recipient must use the reserved example.test domain.")
